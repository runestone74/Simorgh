"""Simorgh art from the approved artwork assets/simorgh/simorgh_art.jpg; the santur icon is drawn by code.

  gen_simorgh_art.py [--font Vazirmatn-Bold.ttf]

Writes assets/simorgh/:
  simorgh_banner.jpg    1600 x 900 README / web banner from simorgh_art.jpg (+ the Persian title with --font, OFL Vazirmatn)
  splash_240.png        240 x 240: what the device shows (120 x 120, 8 colours, dithered, drawn 2x)
  santur_icon_24.png    santur icon preview
and firmware/src/simorgh_splash.h: the splash as 4 bpp pixels + a 16-entry RGB565 palette in the
ST7789's byte order (lcd_blit), drawn by ui_draw.c draw_splash.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageEnhance, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "simorgh"
LAPIS, LAPIS_D, TURQ, TURQ_L = (31, 58, 147), (16, 30, 82), (48, 178, 175), (130, 220, 210)
GOLD, GOLD_D, CREAM, CRIMSON, WHITE = (222, 176, 62), (150, 105, 30), (245, 232, 200), (178, 40, 52), (255, 255, 255)


SRC = OUT / "simorgh_art.jpg"        # the approved artwork (1280 x 720): Simorgh above a santur on a carpet
CROP = (440, 70, 1000, 630)               # square around the bird and the santur (source pixels)


def splash_src():
    """the crop at the stored 120 x 120 (drawn 2x), a little more colour and contrast for 8 colours"""
    im = Image.open(SRC).convert("RGB").crop(CROP).resize((120, 120), Image.LANCZOS)
    return ImageEnhance.Contrast(ImageEnhance.Color(im).enhance(1.3)).enhance(1.15)


def santur_icon(S):
    ss = 8
    im = Image.new("RGBA", (S * ss, S * ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    W = S * ss
    d.polygon([(W * .05, W * .8), (W * .95, W * .8), (W * .75, W * .25), (W * .25, W * .25)], fill=GOLD_D, outline=GOLD)
    for k in range(5):
        y = W * (.32 + k * .1)
        d.line([(W * (.22 - k * .03), y), (W * (.78 + k * .03), y)], fill=CREAM, width=max(1, W // 40))
    d.line([(W * .3, W * .1), (W * .45, W * .5)], fill=TURQ, width=W // 14)  # mezrab
    return im.resize((S, S), Image.LANCZOS)


def rgb565_swapped(c):
    v = ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)
    return ((v >> 8) | (v << 8)) & 0xFFFF


def splash_header(im, path):
    """8 colours, Floyd-Steinberg, 120 x 120: 3 bpp packed LSB-first (5400 B) + an 8-entry RGB565 palette (16 B)
    in the panel's byte order; ui_draw.c draw_splash doubles it to 240 x 240. Returns the 240 x 240 device view."""
    pal_im = im.quantize(8, method=Image.MAXCOVERAGE, kmeans=4)
    q = im.quantize(palette=pal_im, dither=Image.FLOYDSTEINBERG)
    pal = q.getpalette()[:24]
    px = q.tobytes()
    acc = nb = 0
    packed = bytearray()
    for v in px:
        acc |= (v & 7) << nb
        nb += 3
        while nb >= 8:
            packed.append(acc & 255)
            acc >>= 8
            nb -= 8
    if nb:
        packed.append(acc & 255)
    lines = ["/* generated by tools/gen_simorgh_art.py: the Simorgh boot splash, 120 x 120 x 3 bpp, drawn 2x; do not edit */",
             "#define SIMORGH_W 120", "#define SIMORGH_H 120",
             "static const uint16_t SIMORGH_PAL[8] = {" + ", ".join(
                 "0x%04X" % rgb565_swapped(pal[i * 3:i * 3 + 3]) for i in range(8)) + "};",
             "static const uint8_t SIMORGH_PX[%d] = {" % len(packed)]
    for i in range(0, len(packed), 24):
        lines.append("    " + ", ".join("%d" % b for b in packed[i:i + 24]) + ",")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n")
    print(f"simorgh splash: {len(packed)} B pixels + 16 B palette = {len(packed) + 16} B")
    # the device view: RGB565 rounding, nearest 2x
    dev = Image.new("RGB", (120, 120))
    def r565(c):
        return ((c[0] >> 3) * 255 // 31, (c[1] >> 2) * 255 // 63, (c[2] >> 3) * 255 // 31)
    dev.putdata([r565(pal[v * 3:v * 3 + 3]) for v in px])
    return dev.resize((240, 240), Image.NEAREST)


def banner(font):
    im = Image.open(SRC).convert("RGB").resize((1600, 900), Image.LANCZOS)
    if font:
        d = ImageDraw.Draw(im, "RGBA")
        d.rounded_rectangle([560, 18, 1040, 150], 24, fill=(16, 30, 82, 200), outline=GOLD, width=3)
        fa = ImageFont.truetype(font, 92, layout_engine=ImageFont.Layout.RAQM)
        d.text((800, 84), "سیمرغ", font=fa, fill=GOLD, anchor="mm", direction="rtl", language="fa")
    return im


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", help="OFL Persian font (Vazirmatn) for the banner's Persian script")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    banner(a.font).save(OUT / "simorgh_banner.jpg", quality=88)
    splash_header(splash_src(), ROOT / "firmware/src/simorgh_splash.h").save(OUT / "splash_240.png")
    santur_icon(24).save(OUT / "santur_icon_24.png")
    santur_icon(256).save(OUT / "santur_icon_256.png")


if __name__ == "__main__":
    main()
